"""Assemble the main figures and Tables 1-3 into one Word review document.

Reads results/figures/main and results/manuscript; writes
results/manuscript/BioLandUS_FiguresTables_Review.docx. Every number in the
tables and captions comes from the pipeline outputs.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd
from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

VERDICT_FILL = {"Robust": "D9EAD3", "Moderate": "FFF2CC", "Large": "F4CCCC", "Stress": "E7E6E6"}
LABELS = {
    "EXP_ABS_50": "US$50", "EXP_ABS_100": "US$100", "EXP_ABS_200": "US$200", "EXP_ABS_300": "US$300",
    "RENT_PARITY_BENCHMARK": "m = 1 (rent parity)", "SUPPORT_ENTRY_REFERENCE": "m = 3.35",
    "SUPPORT_BALANCED_REFERENCE": "m = 6.71 (reference)", "HIGHER_COMPENSATION_200_REFERENCE": "m = 13.42",
    "HIGHER_COMPENSATION_300_REFERENCE": "m = 20.13",
}
TABLE1 = [
    ("Prospective allocation", "Aᴾ, Qᴾ", "POLYSYS, 2023 Billion-Ton, 2041, US$70/dt", "Modelled; held fixed", "Biomass price; siting"),
    ("Compatible land", "B", "Census of Agriculture 2022; suppressed cells completed", "Observed; completed", "Eligibility rules"),
    ("Participation", "p(O)", "Randomized rental-offer experiment", "Experimentally identified", "Payment level"),
    ("Conditional acreage", "s", "Accepted contracts", "Experimentally informed", "Contract terms"),
    ("Behavioural access", "b = p(O)s", "Experimental estimates", "Derived", "—"),
    ("Institutional transmission", "κ", "Model specification (T1)", "Assumed", "Tenure; aggregation; extension"),
    ("Contractual capacity", "K = Bκ", "Capacity–requirement matching", "Derived", "—"),
    ("Payable land rent", "L", "POLYSYS price and yield; published production budget", "External check; upper bound", "Price; cost-share"),
    ("Mobilized biomass", "M_Q", "λ = min(1, K/Aᴾ)", "Derived", "—"),
]


def shade(cell, hex_fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_fill)
    tc_pr.append(shd)


def table(doc, header, rows, widths_cm, fills=None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(header):
        c = t.rows[0].cells[i]
        c.text = ""
        r = c.paragraphs[0].add_run(h)
        r.bold = True
        r.font.size = Pt(8)
        shade(c, "F2F2F2")
    for k, row in enumerate(rows):
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(str(v))
            run.font.size = Pt(8)
            if fills and fills[k] and i == len(row) - 1:
                shade(cells[i], fills[k])
    for row in t.rows:
        for i, w in enumerate(widths_cm):
            row.cells[i].width = Cm(w)
    return t


def caption(doc, bold: str, text: str) -> None:
    p = doc.add_paragraph()
    r = p.add_run(bold + " ")
    r.bold = True
    r.font.size = Pt(9)
    r2 = p.add_run(text)
    r2.font.size = Pt(9)


def note(doc, text: str) -> None:
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.italic = True
    r.font.size = Pt(8)
    r.font.color.rgb = RGBColor(0x52, 0x51, 0x4E)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", type=Path, default=Path("results"))
    parser.add_argument("--output", type=Path, default=Path("results/manuscript/BioLandUS_FiguresTables_Review.docx"))
    args = parser.parse_args()
    R = args.results
    n = pd.read_csv(R / "manuscript/manuscript_numbers.csv").set_index("key")["value"]
    pc = lambda k: f"{100 * n[k]:.1f}%"  # noqa: E731

    doc = Document()
    for s in doc.sections:
        s.left_margin = s.right_margin = Cm(2)
    doc.styles["Normal"].font.name = "Arial"
    doc.styles["Normal"].font.size = Pt(10)
    doc.add_heading("BioLand-US — main figures and tables (review draft)", level=1)
    note(doc, "Generated by scripts/13_build_review_document.py from the pipeline outputs; all numbers are current.")

    figs = [
        ("Fig1_Framework", "Fig. 1.", "BioLand-US framework. Three evidence streams (prospective POLYSYS allocation, "
         "compatible Census land and a randomized landholder experiment) pass two contractual gates: willingness, which "
         "sets contract capacity K = Bκ, and affordability, which asks whether the offer can be paid from biomass revenue. "
         "Capacity is matched to the fixed allocation within each county and land pool without reallocation."),
        ("Fig2_TwoGates", "Fig. 2.", f"The two gates. (a) Participation rises with the randomized annual offer, from "
         f"{pc('participation_p50')} at US$50 to {pc('participation_p300')} at US$300 (circles: categorical margins with "
         f"95% CIs; line and band: smooth model), while the acreage share committed after acceptance stays flat "
         f"(squares; joint offer test p = {n['conditional_share_offer_joint_p']:.2f}). (b) National biomass mobilization "
         f"under rent-indexed offers: willing landholders alone support {pc('MQ_headline')} at m = 6.71 (band: 95% "
         f"paired respondent bootstrap); requiring the offer to be payable from the US$70/dt price lowers this to "
         f"{pc('MQ_headline_affordable_high_cost')}–{pc('MQ_headline_affordable_low_cost')} (high- to low-cost "
         f"budget), and higher multipliers make it worse. (c) Across herbaceous POLYSYS acres, the reference offer "
         f"exceeds the land payment the biomass price can fund. Values in 2012 US dollars; five-year contracts."),
        ("Fig3_Geography", "Fig. 3.", f"Geography of the shortfall at the reference offer (m = 6.71, five-year). "
         f"(a) Unmet biomass, county mean across the three POLYSYS allocation families; grey counties lack rent data. "
         f"(b) Number of allocation families in which a county is a robust top-decile pressure hotspot. (c) Shares of "
         f"national unmet and allocated biomass by state: Texas, Oklahoma and New Mexico hold "
         f"{pc('unmet_share_tx_ok_nm')} of unmet biomass; without them {pc('MQ_headline_excl_tx_ok_nm')} of the remaining "
         f"allocation is supported. The top 10% of counties hold {pc('unmet_top10pct_counties_share')} of the shortfall."),
        ("Fig4_Uncertainty", "Fig. 4.", f"Sources of variation around the reference result ({pc('MQ_headline')}). "
         f"Bars show the range each check produces; they are reported separately and not combined. "
         f"(b) Share of POLYSYS acres and biomass from the two species tested in the experiment."),
    ]
    for name, label, text in figs:
        doc.add_picture(str(R / "figures/main" / f"{name}.png"), width=Cm(17))
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
        caption(doc, label, text)

    doc.add_page_break()
    caption(doc, "Table 1.", "BioLand-US components and evidential basis.")
    table(doc, ["Component", "Symbol", "Evidence", "Status", "Policy lever"], TABLE1, [3.2, 2.0, 5.6, 3.2, 3.0])

    t2 = pd.read_csv(R / "manuscript/table2_mobilization_by_offer.csv")
    rows = []
    for r in t2.itertuples(index=False):
        rows.append((LABELS[r.scenario_id], f"{100 * r.M_Q_central:.1f}",
                     f"{100 * r.boot_p025:.1f}–{100 * r.boot_p975:.1f}", f"{100 * r.unmet_share:.1f}",
                     f"{r.family_range_pp:.1f}", f"{100 * r.within_tested_range_share_of_Q:.0f}",
                     f"{100 * r.M_Q_affordable_high_cost:.0f}–{100 * r.M_Q_affordable_low_cost:.0f}"))
    doc.add_paragraph()
    caption(doc, "Table 2.", "Prospective biomass mobilization under alternative annual rental offers.")
    table(doc, ["Annual offer", "M_Q (%)", "95% bootstrap (%)", "Unmet (%)", "Family range (pp)",
                "Within tested range (%)", "Affordable M_Q (%)"], rows, [3.4, 1.6, 2.6, 1.6, 2.2, 2.4, 2.6])
    note(doc, "Five-year contracts; family-balanced deterministic central values; intervals are behavioural sampling "
              "only (1,000 paired respondent draws). Rows 1–4: uniform national offers; rows 5–9: offers m × local cash "
              "rent. Within tested range: share of biomass offered US$50–300. Affordable M_Q: offers above the payable "
              "land rent refused, high- to low-cost production budget, US$70/dt in 2022 dollars. 2012 US dollars.")

    t3 = pd.read_csv(R / "manuscript/table3_robustness_synthesis.csv")
    rows, fills = [], []
    for r in t3.itertuples(index=False):
        rows.append((r.check, r.what_varies, f"{100 * r.M_Q_low:.1f}–{100 * r.M_Q_high:.1f}",
                     f"{r.largest_shift_pp:.1f}", f"S{str(r.supplement).lstrip('S')}", r.verdict))
        fills.append(next(v for k, v in VERDICT_FILL.items() if r.verdict.startswith(k)))
    doc.add_paragraph()
    caption(doc, "Table 3.", f"Robustness of the reference result (M_Q = {pc('MQ_headline')}, m = 6.71, five-year).")
    table(doc, ["Check", "What varies", "M_Q range (%)", "Largest shift (pp)", "Supplement", "Verdict"], rows,
          [3.6, 4.6, 2.2, 1.8, 1.6, 3.2], fills)
    note(doc, "Each row changes one element and is reported separately; ranges are not combined. Verdict: robust ≤ 5 pp, "
              "moderate 5–15 pp, large > 15 pp shift from the reference.")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    doc.save(args.output)
    print(f"PASS: review document written to {args.output}")


if __name__ == "__main__":
    main()
